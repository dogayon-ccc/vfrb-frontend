// Run: node tools/served-glbs.mjs   (writes tools/glb-extract/served-sha256.json)
// The reference and derived GLBs are served from Cloudinary as Draco-compressed copies (glTF-Transform), so their bytes differ from
// the originals recorded in derived-manifest.json. This records the served copies' SHA-256 next to the originals, after checking
// that each original (from git, before the files left public/) still matches the manifest and that the served copy keeps its
// geometry (sameGeometry below). Any mismatch writes nothing and exits 1. Re-run after re-uploading models.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { ROOT, fetchModels, modelFile } from './modelFiles.mjs';

export const SOURCE_COMMIT = 'd40b50b^'; // the last commit with the original GLBs in public/models
const MANIFEST = path.join(ROOT, 'tools', 'glb-extract', 'derived-manifest.json');
const OUT = path.join(ROOT, 'tools', 'glb-extract', 'served-sha256.json');

const sha = b => crypto.createHash('sha256').update(b).digest('hex');
// Per primitive: attribute names, triangle (index) count, draw mode, vertex count and the POSITION bounds.
function shape(buf) {
  if (buf.toString('ascii', 0, 4) !== 'glTF') return null;
  const j = JSON.parse(buf.subarray(20, 20 + buf.readUInt32LE(12)).toString('utf8'));
  return (j.meshes ?? []).flatMap(m => m.primitives.map(p => {
    const pos = j.accessors[p.attributes.POSITION];
    return { attrs: Object.keys(p.attributes).sort().join(), indices: p.indices != null ? j.accessors[p.indices].count : null, mode: p.mode ?? 4,
      verts: pos.count, min: pos.min, max: pos.max };
  }));
}
// Compression must keep every triangle, attribute and the model's size. Draco splits vertices along non-manifold edges (measured
// 2026-10-21: up to +4.1%, vfrb-derived/blazer-open-front-black, same triangles and bounds), so vertices may grow by at most 5% but
// never shrink, and its position quantisation may move the bounds by at most 0.5% of the model's extent.
function sameGeometry(served, original) {
  const a = shape(served), b = shape(original);
  if (!a || !b || a.length !== b.length) return false;
  return a.every((s, i) => {
    const o = b[i], ext = Math.max(...o.max.map((v, k) => v - o.min[k]));
    return s.attrs === o.attrs && s.indices === o.indices && s.mode === o.mode && s.verts >= o.verts && s.verts <= o.verts * 1.05
      && [...s.min.map((v, k) => v - o.min[k]), ...s.max.map((v, k) => v - o.max[k])].every(d => Math.abs(d) <= ext * 0.005);
  });
}

const man = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
const models = [
  ...Object.entries(man.originals_sha256).map(([id, h]) => [`/models/reference/${id}.glb`, h]),
  ...man.pieces.map(p => [p.glb, p.glb_sha256]),
];
await fetchModels(models.map(([p]) => p));

const out = {}, bad = [];
for (const [p, originalSha] of models) {
  const original = execFileSync('git', ['show', `${SOURCE_COMMIT}:public${p}`], { cwd: ROOT, maxBuffer: 256 << 20 });
  const servedFile = modelFile(p);
  if (sha(original) !== originalSha) { bad.push(`${p}: the git original no longer matches derived-manifest.json`); continue; }
  if (!fs.existsSync(servedFile)) { bad.push(`${p}: not on Cloudinary`); continue; }
  const served = fs.readFileSync(servedFile);
  if (!sameGeometry(served, original)) { bad.push(`${p}: served copy has different geometry from the original`); continue; }
  out[p] = { sha256: sha(served), bytes: served.length, original_sha256: originalSha, original_bytes: original.length };
}

if (bad.length) { console.error(`served GLBs: ${bad.length} problem(s), nothing written:\n  ${bad.join('\n  ')}`); process.exit(1); }
fs.writeFileSync(OUT, JSON.stringify({
  note: 'SHA-256 of the GLBs as served from Cloudinary (Draco-compressed), each tied to its original in derived-manifest.json. Generated by tools/served-glbs.mjs; do not edit by hand.',
  source_commit: SOURCE_COMMIT, models: out,
}, null, 1) + '\n');
const sum = k => Object.values(out).reduce((n, m) => n + m[k], 0);
console.log(`served GLBs: recorded ${Object.keys(out).length} (${(sum('bytes') / 1e6).toFixed(1)} MB served, ${(sum('original_bytes') / 1e6).toFixed(1)} MB originals) in tools/glb-extract/served-sha256.json`);
